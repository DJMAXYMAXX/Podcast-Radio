#!/usr/bin/env python3
"""
Headless Podcast Radio for a Raspberry Pi inside a real radio.

Hardware (see README): a rotary encoder for tuning, a push button for
"restart episode", a speaker via an I2S amp or the headphone jack.
Audio is played by mpv; static is generated by mpv too, no files needed.

Needs server.py running on the same Pi (or set RADIO_SERVER).
Without GPIO (e.g. testing on a laptop) it falls back to the keyboard:
  a / d  tune down / up     A / D  jump stations     r  restart     q  quit

Not yet tested on hardware: treat it as a starting point.
"""

import json
import os
import socket
import subprocess
import sys
import threading
import time
import urllib.request

SERVER = os.environ.get("RADIO_SERVER", "http://localhost:8088")
MIN, MAX, LOCK, FADE = 87.5, 108.5, 0.12, 0.55
STEP = 0.1                      # MHz per encoder click
PIN_A, PIN_B, PIN_BTN = 17, 27, 22


def get(path):
    with urllib.request.urlopen(SERVER + path, timeout=10) as r:
        return json.loads(r.read())


def post(path, body):
    req = urllib.request.Request(SERVER + path, json.dumps(body).encode(),
                                 {"Content-Type": "application/json"})
    try:
        urllib.request.urlopen(req, timeout=5)
    except Exception:
        pass


class Mpv:
    """A long-running mpv we control over its JSON IPC socket."""

    def __init__(self, name, extra):
        self.sock_path = f"/tmp/podradio-{name}.sock"
        if os.path.exists(self.sock_path):
            os.remove(self.sock_path)
        self.proc = subprocess.Popen(
            ["mpv", "--idle=yes", "--no-video", "--really-quiet",
             f"--input-ipc-server={self.sock_path}", *extra])
        for _ in range(50):
            if os.path.exists(self.sock_path):
                break
            time.sleep(0.1)
        self.lock = threading.Lock()

    def cmd(self, *args):
        with self.lock:
            try:
                s = socket.socket(socket.AF_UNIX)
                s.connect(self.sock_path)
                s.sendall((json.dumps({"command": list(args)}) + "\n").encode())
                s.settimeout(1)
                data = s.recv(4096).decode().splitlines()
                s.close()
                for line in data:
                    msg = json.loads(line)
                    if "error" in msg:
                        return msg.get("data")
            except Exception:
                return None

    def get(self, prop):
        return self.cmd("get_property", prop)

    def set(self, prop, value):
        self.cmd("set_property", prop, value)


class Radio:
    def __init__(self):
        self.channels = []
        while not self.channels:
            try:
                info = get("/api/channels")
                if info["status"] == "ready":
                    self.channels = info["channels"]
                    break
                print("server:", info["status"])
            except Exception as e:
                print("waiting for server:", e)
            time.sleep(3)
        self.player = Mpv("show", [])
        self.noise = Mpv("noise", ["--loop=inf", "av://lavfi:anoisesrc=color=pink:amplitude=0.35"])
        self.freq = self.channels[0]["freq"] + 0.3
        self.tuned = None
        self.current = None
        self.replay = False
        self.volume = 85
        self.lock = threading.RLock()
        self.retune_at = None

    # ---- tuning
    def nearest(self):
        c = min(self.channels, key=lambda c: abs(c["freq"] - self.freq))
        return c, abs(c["freq"] - self.freq)

    def set_freq(self, f):
        with self.lock:
            self.freq = max(MIN, min(MAX, round(f, 2)))
            ch, dist = self.nearest()
            s = 1.0 if dist <= LOCK else max(0.0, 1 - (dist - LOCK) / (FADE - LOCK))
            self.player.set("volume", self.volume * s ** 1.6)
            self.noise.set("volume", self.volume * 0.6 * (1 - s))
            if s > 0 and ch["channel"] != self.tuned:
                self.retune_at = (time.time() + 0.25, ch["channel"])   # debounce while turning
            elif s == 0 and self.tuned is not None and dist > FADE + 0.4:
                self.player.cmd("stop")
                self.tuned, self.current = None, None

    def jump(self, direction):
        freqs = sorted(c["freq"] for c in self.channels)
        if direction > 0:
            nxt = next((f for f in freqs if f > self.freq + 0.05), None)
        else:
            nxt = next((f for f in reversed(freqs) if f < self.freq - 0.05), None)
        if nxt:
            self.set_freq(nxt)

    def tune(self, ch):
        try:
            data = get(f"/api/now?ch={ch}")
        except Exception as e:
            print("tune failed:", e)
            return
        with self.lock:
            self.tuned, self.current, self.replay = ch, data, False
            ep = data["episode"]
            print(f"{data['freq']:.1f}  {ep['show']}  |  {ep['title']}")
            self.player.cmd("loadfile", ep["audio"], "replace", f"start={int(data['offset'])}")

    def restart(self):
        with self.lock:
            if self.current:
                self.replay = True
                self.player.cmd("seek", 0, "absolute")
                print("restarting episode")

    # ---- main loop
    def loop(self):
        self.set_freq(self.freq)
        idle_since = None
        while True:
            time.sleep(0.2)
            with self.lock:
                if self.retune_at and time.time() >= self.retune_at[0]:
                    ch = self.retune_at[1]
                    self.retune_at = None
                    threading.Thread(target=self.tune, args=(ch,), daemon=True).start()
                    continue
                if self.tuned is None:
                    continue
                # mpv goes idle when an episode ends (or fails): pick up the broadcast again
                if self.player.get("idle-active") is True:
                    idle_since = idle_since or time.time()
                    if time.time() - idle_since > 1.5:
                        idle_since = None
                        if self.current and not self.replay:
                            pos = self.current["offset"] + (time.time() - self.current["server_time"])
                            post("/api/duration", {"audio": self.current["episode"]["audio"],
                                                   "duration": pos})
                        threading.Thread(target=self.tune, args=(self.tuned,), daemon=True).start()
                else:
                    idle_since = None


def run_gpio(radio):
    from gpiozero import Button, RotaryEncoder
    enc = RotaryEncoder(PIN_A, PIN_B, max_steps=0)
    btn = Button(PIN_BTN)
    last = [enc.steps]

    def rotated():
        d = enc.steps - last[0]
        last[0] = enc.steps
        radio.set_freq(radio.freq + d * STEP)

    enc.when_rotated = rotated
    btn.when_pressed = radio.restart
    radio.loop()


def run_keyboard(radio):
    import termios
    import tty
    threading.Thread(target=radio.loop, daemon=True).start()
    fd = sys.stdin.fileno()
    old = termios.tcgetattr(fd)
    tty.setcbreak(fd)
    try:
        while True:
            k = sys.stdin.read(1)
            if k == "d": radio.set_freq(radio.freq + STEP)
            elif k == "a": radio.set_freq(radio.freq - STEP)
            elif k == "D": radio.jump(1)
            elif k == "A": radio.jump(-1)
            elif k == "r": radio.restart()
            elif k == "q": break
            print(f"\r{radio.freq:5.1f} FM ", end="", flush=True)
    finally:
        termios.tcsetattr(fd, termios.TCSADRAIN, old)
        radio.player.proc.terminate()
        radio.noise.proc.terminate()


if __name__ == "__main__":
    r = Radio()
    try:
        import gpiozero  # noqa: F401
        on_pi = os.path.exists("/sys/class/gpio")
    except ImportError:
        on_pi = False
    (run_gpio if on_pi and "--keyboard" not in sys.argv else run_keyboard)(r)
